#!/usr/bin/env python3
"""Build the self-contained MT5 files from src/.

MetaEditor can only resolve #include <XAU/...> if a whole Include folder was copied to exactly the
right place, which is easy to get wrong. The generated files inline every project include, so each
program is ONE file that compiles wherever it is dropped.

  src/XAU_Oracle.mq5      -> MQL5/Indicators/XAU_Oracle.mq5
  src/XAU_Sniper_EA.mq5   -> MQL5/Experts/XAU_Sniper_EA.mq5
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "src")
TARGETS = {"XAU_Oracle.mq5": "MQL5/Indicators", "XAU_Sniper_EA.mq5": "MQL5/Experts"}

def inline(path, seen):
    out = []
    with open(path, encoding="ascii") as fh:
        for line in fh:
            m = re.match(r'\s*#include\s*(?:<XAU/([^>]+)>|"([^"]+)")', line)
            if m:
                name = m.group(1) or m.group(2)
                if name in seen:
                    continue
                seen.add(name)
                out.append("//==== begin %s ====\n" % name)
                out.append(inline(os.path.join(SRC, name), seen))
                out.append("\n//==== end %s ====\n" % name)
            else:
                out.append(line)
    return "".join(out)

def main():
    for name, dest in TARGETS.items():
        text = inline(os.path.join(SRC, name), set())
        banner = "// GENERATED by research/bundle.py from src/ -- edit the sources in src/, not this file.\n"
        text = banner + text
        bad = [c for c in text if ord(c) > 127]
        if bad:
            sys.exit("non-ASCII characters in %s" % name)
        d = os.path.join(ROOT, dest)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name), "w", encoding="ascii", newline="\n") as fh:
            fh.write(text)
        print("built", os.path.join(dest, name), "(%d lines)" % text.count("\n"))

main()
