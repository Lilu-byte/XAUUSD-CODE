# Writes app/en_ui.js (UI_EN) and app/en_c.js (EN_C) from the frozen translations.
import json,glob,os,re
D='/tmp/claude-0/-home-user/a290f82c-6216-50d1-bfba-3e81a0d181bc/scratchpad/'
ui=json.load(open(D+'en/ui_en.json',encoding='utf8'))
for ln in open(D+'en/ui_extra.tsv',encoding='utf8'):
    if ln.strip(): k,e=ln.rstrip('\n').split('\t',1); ui[k]=e
open(D+'app/en_ui.js','w',encoding='utf8').write('// English interface text, keyed by the Persian text in app.js (tx/trx). Generated by tools/gen_en.py from en/ui_en.json and en/ui_extra.tsv.\nconst UI_EN = '+json.dumps(ui,ensure_ascii=False,separators=(',',':'))+';\n')
# content: en/ct/<group>.tsv (index -> English) against tools/en_src/<group>.tsv (key -> Persian)
cpath=D+'en/content.json'
C=json.load(open(cpath,encoding='utf8')) if os.path.exists(cpath) else {}
for f in sorted(glob.glob(D+'en/ct/*.tsv')):
    g=os.path.basename(f)[:-4]
    src=[l.rstrip('\n').split('\t',1) for l in open(D+'tools/en_src/'+g.split('.')[0]+'.tsv',encoding='utf8') if l.strip()]
    for ln in open(f,encoding='utf8'):
        if not ln.strip(): continue
        i,e=ln.rstrip('\n').split('\t',1); i=int(i)
        k,fa_=src[i]
        C[k]=e.replace('\\n','\n')
json.dump(C,open(cpath,'w',encoding='utf8'),ensure_ascii=False,indent=0)
open(D+'app/en_c.js','w',encoding='utf8').write('// English lesson content, keyed by enKey(Persian text). Generated by tools/gen_en.py from en/content.json.\nconst EN_C = '+json.dumps(C,ensure_ascii=False,separators=(',',':'))+';\n')
print('ui',len(ui),'content',len(C))
